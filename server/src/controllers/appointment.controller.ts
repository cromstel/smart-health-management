export const createAppointment = async (req: AuthRequest, res: Response): Promise<Response | void> => {
  try {
    const { patientId, doctorId, departmentId, appointmentDate, appointmentTime, type, notes, sendReminder } = req.body;
    // `appointments.id` is a BIGINT AUTO_INCREMENT key, so the row id is
    // generated by the database. A uuid was being written into it, which the
    // column rejected.
    const appointmentId = `APP-${String(Date.now()).slice(-6)}`;

    const [result] = await pool.query(
      `INSERT INTO appointments (appointment_id, patient_id, doctor_id, department_id, appointment_date, appointment_time, type, status, notes)
       VALUES (?, ?, ?, ?, ?, ?, ?, 'scheduled', ?)`,
      [appointmentId, patientId, doctorId || null, departmentId || null, appointmentDate, appointmentTime, type || 'Consultation', notes || null]
    );
    const id = (result as ResultSetHeader).insertId;

    if (sendReminder) {
      const reminderDate = new Date(`${appointmentDate}T${appointmentTime}`);
      reminderDate.setHours(reminderDate.getHours() - 1);
      await pool.query(
        'INSERT INTO appointment_reminders (appointment_id, reminder_date) VALUES (?, ?)',
        [id, reminderDate]
      );
    }

    res.status(201).json({ message: 'Appointment created successfully', id, appointmentId });
  } catch (error) {
    console.error('Create appointment error:', error);
    res.status(500).json({ error: 'Failed to create appointment' });
  }
};

// Only these columns may be changed through the API. Without a whitelist any
// request key became a column, which allowed writes to `id`, `appointment_id`
// and the foreign keys.
const ALLOWED_APPOINTMENT_UPDATES = new Set([
  'doctorId',
  'departmentId',
  'appointmentDate',
  'appointmentTime',
  'type',
  'status',
  'notes',
]);

// Frontend field name -> database column name.
const APPOINTMENT_COLUMN_MAP: Record<string, string> = {
  doctorId: 'doctor_id',
  departmentId: 'department_id',
  appointmentDate: 'appointment_date',
  appointmentTime: 'appointment_time',
  type: 'type',
  status: 'status',
  notes: 'notes',
};

// The statuses the appointment can be in. The column holds them in lower
// case, and a request that says "Confirmed" used to be written as it came,
// which the column does not accept.
const APPOINTMENT_STATUSES = ['scheduled', 'confirmed', 'completed', 'cancelled'];

const normalizeAppointmentStatus = (value: unknown): string | null => {
  if (typeof value !== 'string') return null;
  const normalised = value.trim().toLowerCase();
  return APPOINTMENT_STATUSES.includes(normalised) ? normalised : null;
};

export const updateAppointment = async (req: AuthRequest, res: Response): Promise<Response | void> => {
  try {
    const { id } = req.params;
    const updates = req.body ?? {};

    const fields: string[] = [];
    const values: unknown[] = [];
    for (const [key, value] of Object.entries(updates)) {
      if (!ALLOWED_APPOINTMENT_UPDATES.has(key)) continue;
      if (key === 'status') {
        const status = normalizeAppointmentStatus(value);
        if (status === null) {
          res.status(400).json({
            error: `Status must be one of: ${APPOINTMENT_STATUSES.join(', ')}`,
          });
          return;
        }
        fields.push(`${APPOINTMENT_COLUMN_MAP[key]} = ?`);
        values.push(status);
        continue;
      }
      fields.push(`${APPOINTMENT_COLUMN_MAP[key]} = ?`);
      values.push(value === '' ? null : value);
    }

    if (fields.length === 0) {
      res.status(400).json({ error: 'No updatable fields provided' });
      return;
    }

    await pool.query(`UPDATE appointments SET ${fields.join(', ')} WHERE id = ?`, [...values, id]);
    res.json({ message: 'Appointment updated successfully' });
  } catch (error) {
    console.error('Update appointment error:', error);
    res.status(500).json({ error: 'Failed to update appointment' });
  }
};

