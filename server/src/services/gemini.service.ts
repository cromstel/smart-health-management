/**
 * Gemini AI service.
 *
 * Talks to the Google Generative Language REST API directly with fetch -- the
 * server has no @google/generative-ai dependency and no new one was added for
 * this feature.
 *
 * Two rules shape this module:
 *  1. The client contract carries a `simulated` flag. When the API key is
 *     missing or the upstream call fails, a clearly labelled placeholder is
 *     returned instead of an error, so the UI can show the simulated branch
 *     rather than a dead page.
 *  2. No patient data leaves the system unless it was explicitly allowed.
 *     `GEMINI_SEND_PHI` gates the insights endpoint: when it is not "true" the
 *     server computes the insight locally and never calls out.
 */
import { computeVitalStatus, extractRecordAlerts } from './vitals.service.js';
import type { VitalsRecord } from './vitals.service.js';
import { isConfigured } from '../config/env.js';

const GEMINI_ENDPOINT = 'https://generativelanguage.googleapis.com/v1beta/models';
// The free tier of the API can take the better part of a minute to answer, so
// the request budget is generous. It is configurable because a paid tier is
// much faster and a self-hosted deployment may sit behind a slow proxy.
const REQUEST_TIMEOUT_MS = Number(process.env.GEMINI_TIMEOUT_MS || '120000');

export type GeminiModelType = 'pro' | 'flash' | 'lite';

export interface GeminiChatMessage {
  role: string;
  content: string;
}

export interface GeminiGroundingMetadata {
  searchQueries?: string[];
  sources?: { title: string; uri: string }[];
  grounded?: boolean;
}

export interface GeminiResult {
  text: string;
  modelUsed: string;
  simulated: boolean;
  groundingMetadata: GeminiGroundingMetadata;
}

const MODEL_BY_TYPE: Record<GeminiModelType, string> = {
  pro: process.env.GEMINI_MODEL_PRO || 'gemini-3.1-pro-preview',
  flash: process.env.GEMINI_MODEL_FLASH || 'gemini-3.8-flash',
  lite: process.env.GEMINI_MODEL_LITE || 'gemini-3.5-flash-lite',
};

export const DEFAULT_MODEL = MODEL_BY_TYPE.flash;

/**
 * Resolve the requested model to a concrete model id.
 *
 * Only a known alias or a well formed "gemini-*" id is accepted: the value
 * ends up in the request path, so it must never be able to point somewhere
 * else. The defaults are overridable with GEMINI_MODEL_PRO / _FLASH / _LITE
 * because the model lineup moves quickly and the 2.5 family is already
 * retired for new API keys.
 */
export function resolveModel(modelType?: string): string {
  const raw = String(modelType ?? '').trim().toLowerCase();
  if (!raw) return DEFAULT_MODEL;
  if (raw in MODEL_BY_TYPE) return MODEL_BY_TYPE[raw as GeminiModelType];
  if (/^gemini[a-z0-9._-]{0,50}$/.test(raw)) return raw;
  return DEFAULT_MODEL;
}

export function isGeminiConfigured(): boolean {
  // A placeholder is not a key: the environment files carry one for every
  // integration that is not switched on.
  return isConfigured(process.env.GEMINI_API_KEY);
}

/**
 * Whether patient data may be sent to the external model.
 *
 * Off by default: an outbound call to a third-party API is a PHI disclosure
 * decision, so it has to be taken deliberately and configured, not inherited
 * from the presence of an API key.
 */
export function isPhiSendingAllowed(): boolean {
  return String(process.env.GEMINI_SEND_PHI ?? '').trim().toLowerCase() === 'true';
}

function simulatedText(reason: string): string {
  return [
    '⚠️ **SIMULATED RESPONSE — NOT GENERATED BY THE AI MODEL**',
    '',
    'The clinical AI service is unavailable in this environment, so no model output could be produced.',
    'This placeholder is shown instead of an answer and must not be read as clinical guidance or as AI output.',
    '',
    `*Reason: ${reason}*`,
    '',
    'Set `GEMINI_API_KEY` in the server environment to enable live reasoning with Google Search grounding.',
  ].join('\n');
}

function simulatedResult(reason: string, modelUsed: string): GeminiResult {
  return {
    text: simulatedText(reason),
    modelUsed,
    simulated: true,
    groundingMetadata: { grounded: false },
  };
}

function toContents(messages: GeminiChatMessage[]): { role: string; parts: { text: string }[] }[] {
  return messages
    .filter((m) => typeof m?.content === 'string' && m.content.trim() !== '')
    .map((m) => ({
      role: m.role === 'assistant' || m.role === 'model' ? 'model' : 'user',
      parts: [{ text: m.content }],
    }));
}

function extractGrounding(candidate: any): GeminiGroundingMetadata {
  const grounding = candidate?.groundingMetadata;
  if (!grounding) return { grounded: false };

  const searchQueries: string[] = Array.isArray(grounding.googleSearchQueries)
    ? grounding.googleSearchQueries.filter((q: unknown) => typeof q === 'string')
    : [];

  const sources: { title: string; uri: string }[] = Array.isArray(grounding.groundingChunks)
    ? grounding.groundingChunks
        .map((chunk: any) => chunk?.web)
        .filter((web: any) => web && web.uri)
        .map((web: any) => ({ title: String(web.title || web.uri), uri: String(web.uri) }))
    : [];

  return { searchQueries, sources, grounded: true };
}

interface CallOptions {
  model: string;
  contents: { role: string; parts: { text: string }[] }[];
  systemInstruction?: string;
  enableSearchGrounding?: boolean;
}

async function callGemini(options: CallOptions): Promise<GeminiResult> {
  const apiKey = String(process.env.GEMINI_API_KEY ?? '').trim();
  if (!apiKey) {
    return simulatedResult('GEMINI_API_KEY is not configured on the server.', options.model);
  }

  const body: Record<string, unknown> = {
    contents: options.contents,
  };

  // The system instruction is passed as a system instruction -- it is never
  // concatenated into a user turn, so the model can tell the two apart.
  if (options.systemInstruction && options.systemInstruction.trim() !== '') {
    body.systemInstruction = { parts: [{ text: options.systemInstruction }] };
  }

  if (options.enableSearchGrounding) {
    body.tools = [{ googleSearch: {} }];
  }

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  try {
    const response = await fetch(
      `${GEMINI_ENDPOINT}/${options.model}:generateContent?key=${encodeURIComponent(apiKey)}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body),
        signal: controller.signal,
      }
    );

    const data: any = await response.json().catch(() => null);

    if (!response.ok) {
      const upstreamMessage =
        typeof data?.error?.message === 'string' ? data.error.message : `HTTP ${response.status}`;
      console.error(`Gemini request failed (${response.status}): ${upstreamMessage}`);
      return simulatedResult(`The Gemini API request failed (${upstreamMessage}).`, options.model);
    }

    const candidate = data?.candidates?.[0];
    const parts = candidate?.content?.parts;
    const text = Array.isArray(parts)
      ? parts
          .map((part: any) => (typeof part?.text === 'string' ? part.text : ''))
          .join('')
          .trim()
      : '';

    if (!text) {
      return simulatedResult('The Gemini API returned an empty response.', options.model);
    }

    return {
      text,
      modelUsed: options.model,
      simulated: false,
      groundingMetadata: extractGrounding(candidate),
    };
  } catch (error) {
    const reason = error instanceof Error ? error.message : 'Unknown network error';
    console.error(`Gemini request error: ${reason}`);
    return simulatedResult(`The Gemini API request could not be completed (${reason}).`, options.model);
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Chat completion for the AI assistant page.
 */
export async function chat(params: {
  messages: GeminiChatMessage[];
  modelType?: string;
  systemInstruction?: string;
  enableSearchGrounding?: boolean;
}): Promise<GeminiResult> {
  const model = resolveModel(params.modelType);
  const contents = toContents(params.messages ?? []);

  if (contents.length === 0) {
    return {
      text: 'No question was submitted, so there was nothing for the model to answer.',
      modelUsed: model,
      simulated: true,
      groundingMetadata: { grounded: false },
    };
  }

  return callGemini({
    model,
    contents,
    systemInstruction: params.systemInstruction,
    enableSearchGrounding: params.enableSearchGrounding,
  });
}

function formatNumber(value: number, unit: string): string {
  return `${value} ${unit}`;
}

/**
 * Build the clinical insight from the recorded vitals, locally.
 *
 * This is the default path for /api/gemini/insights: it produces a genuinely
 * useful, rule based summary without any patient data leaving the server.
 */
export function buildLocalInsight(vitalsList: VitalsRecord[]): string {
  const records = [...vitalsList].sort(
    (a, b) => new Date(b.recordedAt).getTime() - new Date(a.recordedAt).getTime()
  );
  const latest = records[0];

  if (!latest) {
    return [
      '### No clinical readings available',
      '',
      '*No vital signs have been recorded for this patient yet, so no insight can be derived.*',
    ].join('\n');
  }

  const status = computeVitalStatus(
    latest.systolicBp,
    latest.diastolicBp,
    latest.heartRate,
    latest.temperature
  );
  const alerts = extractRecordAlerts(latest);

  const lines: string[] = [];
  lines.push('### Rule-based clinical summary (not AI-generated)');
  lines.push('');
  lines.push(
    '*Computed on the server from the recorded vitals using the configured clinical thresholds. No patient data was sent to an external service.*'
  );
  lines.push('');
  lines.push(`**Latest reading (${latest.recordedAt}) — status: ${status.toUpperCase()}**`);
  lines.push('');
  lines.push(
    `* Blood pressure: ${formatNumber(latest.systolicBp, 'mmHg systolic')} / ${formatNumber(
      latest.diastolicBp,
      'mmHg diastolic'
    )}`
  );
  lines.push(`* Heart rate: ${formatNumber(latest.heartRate, 'bpm')}`);
  lines.push(`* Temperature: ${formatNumber(latest.temperature, 'C')}`);
  if (latest.respiratoryRate !== undefined) {
    lines.push(`* Respiratory rate: ${formatNumber(latest.respiratoryRate, 'breaths/min')}`);
  }
  if (latest.oxygenSaturation !== undefined) {
    lines.push(`* Oxygen saturation: ${formatNumber(latest.oxygenSaturation, '%')}`);
  }
  lines.push('');

  if (alerts.length > 0) {
    lines.push(`**Active alerts (${alerts.length})**`);
    lines.push('');
    for (const alert of alerts) {
      lines.push(`* [${alert.severity.toUpperCase()}] ${alert.title} — ${alert.metricValue}`);
      lines.push(`  * ${alert.recommendedAction}`);
    }
    lines.push('');
  } else {
    lines.push('**Active alerts (0)**');
    lines.push('');
    lines.push('* No threshold was crossed by the latest reading.');
    lines.push('');
  }

  if (records.length > 1) {
    const previous = records[1];
    const systolicDelta = latest.systolicBp - previous.systolicBp;
    const heartRateDelta = latest.heartRate - previous.heartRate;
    lines.push('**Trend against the previous reading**');
    lines.push('');
    lines.push(
      `* Systolic blood pressure ${systolicDelta === 0 ? 'unchanged' : systolicDelta > 0 ? `up ${systolicDelta} mmHg` : `down ${Math.abs(systolicDelta)} mmHg`}.`
    );
    lines.push(
      `* Heart rate ${heartRateDelta === 0 ? 'unchanged' : heartRateDelta > 0 ? `up ${heartRateDelta} bpm` : `down ${Math.abs(heartRateDelta)} bpm`}.`
    );
    lines.push('');
  }

  lines.push(
    'DISCLAIMER: This is a deterministic threshold summary generated by the application, not an AI assessment. It is a clinical aid for licensed professionals and does not replace independent clinical judgment or direct patient examination.'
  );

  return lines.join('\n');
}

/**
 * Clinical insight for a patient's vitals.
 *
 * With `GEMINI_SEND_PHI=false` (the default) nothing is sent to Google: the
 * insight is computed locally and returned with `simulated: true`, so the UI
 * labels it as such. With `GEMINI_SEND_PHI=true` the vitals are sent to the
 * model and the outbound disclosure is logged.
 */
export async function clinicalInsights(params: {
  patientId?: string;
  patientName?: string;
  vitalsList: VitalsRecord[];
}): Promise<GeminiResult> {
  const vitalsList = Array.isArray(params.vitalsList) ? params.vitalsList : [];

  if (!isPhiSendingAllowed()) {
    return {
      text: buildLocalInsight(vitalsList),
      modelUsed: 'local-clinical-rules',
      simulated: true,
      groundingMetadata: { grounded: false },
    };
  }

  if (!isGeminiConfigured()) {
    return simulatedResult('GEMINI_API_KEY is not configured on the server.', DEFAULT_MODEL);
  }

  const readings = vitalsList
    .slice(0, 20)
    .map(
      (v) =>
        `- ${v.recordedAt}: BP ${v.systolicBp}/${v.diastolicBp} mmHg, HR ${v.heartRate} bpm, temp ${v.temperature} C` +
        (v.oxygenSaturation !== undefined ? `, SpO2 ${v.oxygenSaturation}%` : '') +
        (v.respiratoryRate !== undefined ? `, RR ${v.respiratoryRate}/min` : '')
    )
    .join('\n');

  console.warn(
    'GEMINI_SEND_PHI is enabled: patient vitals are being sent to the external Gemini API.'
  );

  return callGemini({
    model: DEFAULT_MODEL,
    contents: [
      {
        role: 'user',
        parts: [
          {
            text: [
              'Summarise the clinical trend of the following recorded vital signs and list the readings that crossed a clinical threshold.',
              'Do not give a diagnosis; describe the observations and the thresholds that were crossed.',
              '',
              readings,
            ].join('\n'),
          },
        ],
      },
    ],
    systemInstruction:
      'You are a clinical assistant supporting licensed healthcare professionals. Describe observations and thresholds only. Never state a definitive diagnosis. Always append the standard disclaimer: "DISCLAIMER: This analysis is an AI-generated clinical aid for licensed professionals. It does not replace independent clinical judgment or direct patient examination."',
    enableSearchGrounding: false,
  });
}
